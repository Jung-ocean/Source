function plot_arctic_map(ax)

% Map projection
if nargin < 1
    ax = axesm('stereo', ...
        'Origin', [90 0 0], ...
        'MapLatLimit', [65 90], ...
        'Frame', 'on', ...
        'Grid', 'off');
else
    axes(ax);

    ax = axesm('stereo', ...
        'Origin', [90 0 0], ...
        'MapLatLimit', [65 90], ...
        'Frame', 'on', ...
        'Grid', 'off');
end

axis off;
hold on;

% Land areas
land = shaperead('landareas.shp', 'UseGeoCoords', true);
geoshow(land, ...
    'DisplayType', 'polygon', ...
    'FaceColor', [0.8 0.8 0.8], ...
    'EdgeColor', [0.3 0.3 0.3]);

% Latitude 75°N
lon = linspace(-180, 180, 1000);
lat75 = 75 * ones(size(lon));

geoshow(lat75, lon, ...
    'DisplayType', 'line', ...
    'Color', 'k', ...
    'LineStyle', '--', ...
    'LineWidth', 0.1);

% Longitude lines
lat = linspace(65, 89.99, 500);
meridians = [90, 0, -90, 180];

for k = 1:length(meridians)
    lonLine = meridians(k) * ones(size(lat));

    geoshow(lat, lonLine, ...
        'DisplayType', 'line', ...
        'Color', 'k', ...
        'LineStyle', '--', ...
        'LineWidth', 0.1);
end

% Labels
fs = 10;

textm(75, 181, '75°N', ...
    'FontSize', fs, ...
    'Color', 'k', ...
    'HorizontalAlignment', 'right', ...
    'VerticalAlignment', 'bottom');

textm(67, 90, '90°E', ...
    'FontSize', fs, ...
    'Color', 'k', ...
    'HorizontalAlignment', 'right', ...
    'VerticalAlignment', 'top');

textm(67, -90, '90°W', ...
    'FontSize', fs, ...
    'Color', 'k', ...
    'HorizontalAlignment', 'left', ...
    'VerticalAlignment', 'top');

textm(66.5, 2, '0°E', ...
    'FontSize', fs, ...
    'Color', 'k', ...
    'HorizontalAlignment', 'left', ...
    'VerticalAlignment', 'bottom');

tightmap;

end